alter table orders
  add column if not exists order_number     bigint generated by default as identity (start with 1001),
  add column if not exists order_type       text not null default 'pickup',
  add column if not exists payment_method   text not null default 'cash',
  add column if not exists delivery_address text;

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'orders_order_type_check') then
    alter table orders add constraint orders_order_type_check
      check (order_type in ('pickup', 'delivery'));
  end if;
  if not exists (select 1 from pg_constraint where conname = 'orders_payment_method_check') then
    alter table orders add constraint orders_payment_method_check
      check (payment_method in ('cash', 'upi'));
  end if;
  if not exists (select 1 from pg_constraint where conname = 'orders_delivery_needs_address') then
    alter table orders add constraint orders_delivery_needs_address
      check (order_type <> 'delivery' or delivery_address is not null);
  end if;
end $$;

create unique index if not exists idx_orders_order_number on orders(order_number);

-- VERIFY — should list the 4 new columns
select column_name, data_type
from information_schema.columns
where table_name = 'orders'
  and column_name in ('order_number', 'order_type', 'payment_method', 'delivery_address')
order by column_name;
